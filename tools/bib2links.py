#!/usr/bin/env python3
"""Pull links and preview images out of a BibTeX file into _data/pub_links.yml.

Usage (from the repo root):
    python3 tools/bib2links.py path/to/papers.bib

Entries are matched to _data/publications.yml by title (case and punctuation ignored).
No third-party packages needed. Unmatched bib entries are reported so you can fix them by hand.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUBS = ROOT / "_data" / "publications.yml"
OUT = ROOT / "_data" / "pub_links.yml"


def norm(title):
    return re.sub(r"[^a-z0-9]", "", title.lower())


def parse_bib(text):
    """Return a list of dicts with the fields of each @entry."""
    entries, i = [], 0
    while True:
        m = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", re.S).search(text, i)
        if not m:
            break
        if m.group(1).lower() in ("comment", "string", "preamble"):
            i = m.end()
            continue
        j, depth = m.end(), 1
        while j < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        body = text[m.end(): j - 1]
        fields, k = {"_key": m.group(2)}, 0
        for fm in re.finditer(r"(\w+)\s*=\s*", body):
            if fm.start() < k:
                continue
            name, k = fm.group(1).lower(), fm.end()
            if k < len(body) and body[k] == "{":
                d, s = 1, k + 1
                k += 1
                while k < len(body) and d:
                    d += {"{": 1, "}": -1}.get(body[k], 0)
                    k += 1
                value = body[s: k - 1]
            elif k < len(body) and body[k] == '"':
                e = body.index('"', k + 1)
                value, k = body[k + 1: e], e + 1
            else:
                e = re.compile(r"[,\n]").search(body, k)
                e = e.start() if e else len(body)
                value, k = body[k:e], e
            fields[name] = re.sub(r"\s+", " ", value.replace("{", "").replace("}", "")).strip()
        entries.append(fields)
        i = j
    return entries


def as_url(value, folder):
    if re.match(r"^https?://", value) or value.startswith("/"):
        return value
    return f"/assets/{folder}/{value}"


def links_for(e):
    out = {}
    if e.get("html"):
        out["paper"] = e["html"]
    elif e.get("pdf"):
        out["paper"] = as_url(e["pdf"], "pdf")
    if e.get("arxiv"):
        out["arxiv"] = e["arxiv"] if e["arxiv"].startswith("http") else f"https://arxiv.org/abs/{e['arxiv']}"
    for src, dst in (("code", "code"), ("website", "project"), ("video", "video"), ("slides", "slides"), ("poster", "poster")):
        if e.get(src):
            out[dst] = as_url(e[src], "pdf") if dst in ("slides", "poster") else e[src]
    if e.get("preview"):
        out["preview"] = as_url(e["preview"], "img/publication_preview")
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    bib = parse_bib(Path(sys.argv[1]).read_text(encoding="utf-8"))
    pubs = re.findall(r"^- key:\s*(\S+)\s*\n\s+title:\s*\"?(.+?)\"?\s*$", PUBS.read_text(encoding="utf-8"), re.M)
    by_title = {norm(t): k for k, t in pubs}
    lines, unmatched = ["# Generated by tools/bib2links.py. Safe to edit by hand.\n"], []
    for e in bib:
        key = by_title.get(norm(e.get("title", "")))
        if not key:
            unmatched.append(e.get("title", e["_key"]))
            continue
        links = links_for(e)
        if not links:
            continue
        lines.append(f"{key}:\n")
        for f, v in links.items():
            lines.append(f'  {f}: "{v}"\n')
    OUT.write_text("".join(lines) if len(lines) > 1 else "{}\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(lines) - 1} lines).")
    for t in unmatched:
        print(f"  not matched: {t}")


if __name__ == "__main__":
    main()
